// Uploads every sprite sheet in public/sprites to Cloudinary and regenerates
// src/sprite-urls.ts with the returned (versioned, immutable) delivery URLs.
//
// Credentials come from CLOUDINARY_URL=cloudinary://<api_key>:<api_secret>@<cloud_name>
// (copy it from the Cloudinary dashboard into package/sprites/.env).
//
//   npm run upload-sprites

import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SPRITES_DIR = join(here, "../../../public/sprites");
const OUTPUT_FILE = join(here, "../src/sprite-urls.ts");
const FOLDER = "claudesprites";

const { CLOUDINARY_URL } = process.env;
if (!CLOUDINARY_URL) {
  console.error("Missing CLOUDINARY_URL. Add it to package/sprites/.env.");
  process.exit(1);
}
const creds = new URL(CLOUDINARY_URL);
const apiKey = decodeURIComponent(creds.username);
const apiSecret = decodeURIComponent(creds.password);
const cloudName = creds.hostname;

const sign = (params) => {
  const toSign = Object.keys(params)
    .sort()
    .map((k) => `${k}=${params[k]}`)
    .join("&");
  return createHash("sha1").update(toSign + apiSecret).digest("hex");
};

const upload = async (id, file) => {
  const params = {
    public_id: `${FOLDER}/c${id}`,
    overwrite: "true",
    invalidate: "true",
    timestamp: Math.floor(Date.now() / 1000),
  };
  const form = new FormData();
  for (const [k, v] of Object.entries(params)) form.append(k, String(v));
  form.append("api_key", apiKey);
  form.append("signature", sign(params));
  form.append("file", new Blob([await readFile(file)], { type: "image/png" }));

  const res = await fetch(
    `https://api.cloudinary.com/v1_1/${cloudName}/image/upload`,
    { method: "POST", body: form },
  );
  const body = await res.json();
  if (!res.ok) throw new Error(`c${id}.png: ${body.error?.message ?? res.status}`);
  return body.secure_url;
};

const ids = (await readdir(SPRITES_DIR))
  .map((f) => f.match(/^c(\d+)\.png$/)?.[1])
  .filter(Boolean)
  .map(Number)
  .sort((a, b) => a - b);

const urls = {};
for (const id of ids) {
  urls[id] = await upload(id, join(SPRITES_DIR, `c${id}.png`));
  console.log(`✓ c${id}.png → ${urls[id]}`);
}

const lines = ids.map((id) => `  ${id}: "${urls[id]}",`).join("\n");
await writeFile(
  OUTPUT_FILE,
  `// Generated by scripts/upload-sprites.mjs — do not edit by hand.\nexport const SPRITE_SHEET_URLS: Record<number, string> = {\n${lines}\n};\n`,
);
console.log(`\nWrote ${ids.length} URLs to src/sprite-urls.ts`);
